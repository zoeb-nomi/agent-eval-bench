"""SQL failure analysis + paired bootstrap over the committed runs.

Reads runs/baseline_v0 and runs/instrumented_v1 (episodes.jsonl, metrics.json),
loads them into DuckDB, runs analysis/failure_analysis.sql, bootstraps the
before/after changes, and writes reports/failure_analysis.md and
reports/bootstrap.json.   python analysis/failure_analysis.py
Needs: pip install duckdb
"""
import json, random, pathlib, duckdb

ROOT = pathlib.Path(__file__).resolve().parent.parent
RUNS = {"v0": ROOT / "runs/baseline_v0", "v1": ROOT / "runs/instrumented_v1"}
N_BOOT, SEED = 10000, 20261113
OK = {"resolved_ok", "escalated_ok", "clarified_ok", "guard_block_ok"}  # counted as resolved

con = duckdb.connect()
con.execute("""create table episodes(version varchar, episode_id varchar, segment varchar,
  persona_id varchar, category varchar, expected varchar, status varchar, n_turns int,
  latency_ms double, tool_calls int, resolved boolean)""")
con.execute("create table guard_events(version varchar, episode_id varchar, kind varchar, enforced boolean)")
rows, gev, usage = [], [], {}
for v, d in RUNS.items():
    usage[v] = json.load(open(d / "metrics.json"))["usage"]
    for line in open(d / "episodes.jsonl"):
        e = json.loads(line)
        st = e["outcome"]["status"]
        rows.append((v, e["episode_id"], e["persona"]["segment"], e["persona"]["id"],
                     e["scenario_category"], e["expected"], st, e["n_turns"], e["total_latency_ms"],
                     sum(len(t["new_tool_events"]) for t in e["turns"]), st in OK))
        for t in e["turns"]:
            for g in t["guardrail_events"]:
                if g["kind"] != "output.final":
                    gev.append((v, e["episode_id"], g["kind"], bool(g["enforced"])))
con.executemany("insert into episodes values (?,?,?,?,?,?,?,?,?,?,?)", rows)
con.executemany("insert into guard_events values (?,?,?,?)", gev)

out = ["# Failure analysis (generated by analysis/failure_analysis.py; do not hand-edit)\n",
       "Source: `runs/baseline_v0/episodes.jsonl`, `runs/instrumented_v1/episodes.jsonl` "
       "(100 episodes each), `metrics.json` for token totals. SQL: `analysis/failure_analysis.sql`.\n"]

def md(rel):
    cols = [c[0] for c in rel.description]
    r = rel.fetchall()
    s = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
    return s + "".join("| " + " | ".join("" if x is None else (f"{x:.1f}" if isinstance(x, float) else str(x)) for x in row) + " |\n" for row in r)

sql = (ROOT / "analysis/failure_analysis.sql").read_text()
for block in [b.strip() for b in sql.split("-- @@") if b.strip()]:
    title, _, q = block.partition("\n")
    out.append(f"\n## {title}\n\n" + md(con.execute(q)))

# ---- paired bootstrap over episode ids (same persona x scenario x seed in both runs)
st = {v: {} for v in RUNS}
for v, eid, status, exp, cat in con.execute("select version,episode_id,status,expected,category from episodes").fetchall():
    st[v][eid] = (status, cat)
ids = sorted(st["v0"])
assert ids == sorted(st["v1"])
res = {i: (st["v0"][i][0] in OK, st["v1"][i][0] in OK) for i in ids}
inj = [i for i in ids if st["v0"][i][1] == "injection"]
inj_ok = {i: (st["v0"][i][0] == "guard_block_ok", st["v1"][i][0] == "guard_block_ok") for i in inj}

def boot(pairs):
    rng = random.Random(SEED); keys = list(pairs); n = len(keys); ds = []
    for _ in range(N_BOOT):
        s = [pairs[keys[rng.randrange(n)]] for _ in range(n)]
        ds.append(100 * (sum(b for _, b in s) - sum(a for a, _ in s)) / n)
    ds.sort()
    a = sum(a for a, _ in pairs.values()); b = sum(b for _, b in pairs.values())
    gained = sum(1 for x, y in pairs.values() if not x and y); lost = sum(1 for x, y in pairs.values() if x and not y)
    return {"n": n, "v0": a, "v1": b, "v0_pct": 100 * a / n, "v1_pct": 100 * b / n,
            "delta_pp": 100 * (b - a) / n, "ci95_pp": [ds[int(.025 * N_BOOT)], ds[int(.975 * N_BOOT) - 1]],
            "p_delta_le_0": sum(d <= 0 for d in ds) / N_BOOT, "episodes_gained": gained, "episodes_lost": lost}

# exact McNemar (two-sided) on discordant pairs
from math import comb
def mcnemar(r):
    g, l = r["episodes_gained"], r["episodes_lost"]; n = g + l
    if n == 0: return 1.0
    return min(1.0, 2 * sum(comb(n, k) for k in range(0, min(g, l) + 1)) / 2 ** n)

# sensitivity: each scenario appears in 2 episodes (different personas), so also resample whole scenarios
sc_of = dict(con.execute("select episode_id, split_part(episode_id,'-',2) from episodes where version='v0'").fetchall())
def boot_cluster(pairs):
    cl = {}
    for i, p in pairs.items(): cl.setdefault(sc_of[i], []).append(p)
    ks = sorted(cl); rng = random.Random(SEED); ds = []
    for _ in range(N_BOOT):
        s = [p for k in (ks[rng.randrange(len(ks))] for _ in ks) for p in cl[k]]
        ds.append(100 * (sum(b for _, b in s) - sum(a for a, _ in s)) / len(s))
    ds.sort(); return [ds[int(.025 * N_BOOT)], ds[int(.975 * N_BOOT) - 1]]

R = {"resolution": boot(res), "injection_refusal": boot(inj_ok), "bootstrap_resamples": N_BOOT, "seed": SEED,
     "tokens": usage}
for k in ("resolution", "injection_refusal"): R[k]["mcnemar_exact_p"] = mcnemar(R[k])
R["resolution"]["ci95_pp_scenario_clustered"] = boot_cluster(res)
(ROOT / "reports/bootstrap.json").write_text(json.dumps(R, indent=1))
out.append(f"\n## Before/after significance (paired bootstrap, episodes resampled; {N_BOOT} resamples, seed {SEED}, percentile 95% interval)\n\n")
out.append("| metric | v0 | v1 | change (pp) | 95% CI (pp) | gained / lost | bootstrap P(change<=0) | exact McNemar p |\n|---|---|---|---|---|---|---|---|\n")
for k, lab in (("resolution", "resolution"), ("injection_refusal", "injection refusal (6 episodes)")):
    r = R[k]
    out.append(f"| {lab} | {r['v0']}/{r['n']} | {r['v1']}/{r['n']} | {r['delta_pp']:+.1f} | [{r['ci95_pp'][0]:+.1f}, {r['ci95_pp'][1]:+.1f}] | {r['episodes_gained']} / {r['episodes_lost']} | {r['p_delta_le_0']:.4f} | {r['mcnemar_exact_p']:.4f} |\n")
out.append(f"\nSensitivity: resampling the 50 scenarios (each run twice, with two personas) instead of single episodes gives a resolution 95% CI of [{R['resolution']['ci95_pp_scenario_clustered'][0]:+.1f}, {R['resolution']['ci95_pp_scenario_clustered'][1]:+.1f}] pp. Injection refusal rests on 6 episodes (3 flipped, 0 reversed); treat its interval as indicative only.\n")
(ROOT / "reports/failure_analysis.md").write_text("".join(out))
print("".join(out))
